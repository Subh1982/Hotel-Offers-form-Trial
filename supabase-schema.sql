create table if not exists public.offer_submissions (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  generated_at timestamptz,
  email text,
  person_in_charge_name text,
  hotel_rid_code text,
  hotel_name text,
  city_country text,
  offer_type text,
  offer_tile_title text,
  offer_banner_title text,
  offer_subtitle text,
  offer_description text,
  meta_description text,
  offer_details jsonb not null default '{}'::jsonb,
  booking_link text,
  terms text,
  translations jsonb not null default '{}'::jsonb,
  auto_translations jsonb not null default '{}'::jsonb,
  files jsonb not null default '{}'::jsonb,
  department_confirmation text,
  acknowledgement text,
  status text not null default 'submitted'
);

